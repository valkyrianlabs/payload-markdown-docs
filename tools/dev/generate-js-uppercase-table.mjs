#!/usr/bin/env node
// Generates cli/src/js_uppercase_table.inc: the String.prototype.toUpperCase()
// mapping for every non-ASCII BMP code unit whose upper-case form differs.
// pmdocs uses it to upper-case the first UTF-16 code unit of filename-derived
// titles exactly like the server (src/sync/frontmatter.ts titleFromSourcePath).
//
//   node tools/dev/generate-js-uppercase-table.mjs > cli/src/js_uppercase_table.inc
const lines = []

for (let code = 0x80; code <= 0xffff; code += 1) {
  if (code >= 0xd800 && code <= 0xdfff) {
    continue
  }

  const character = String.fromCharCode(code)
  const upper = character.toUpperCase()

  if (upper !== character) {
    const bytes = [...Buffer.from(upper, 'utf8')].map((byte) => `\\x${byte.toString(16).padStart(2, '0')}`).join('')
    lines.push(`  {0x${code.toString(16).padStart(4, '0')}, "${bytes}"},`)
  }
}

process.stdout.write(
  [
    `// Generated by tools/dev/generate-js-uppercase-table.mjs with Node ${process.versions.node}`,
    `// (Unicode ${process.versions.unicode}). Do not edit by hand.`,
    ...lines,
    '',
  ].join('\n'),
)
